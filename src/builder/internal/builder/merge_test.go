func TestTitleExtendsOnlyWhereTheSeriesNameCarriesOn(t *testing.T) {
	db := offlineFromJSON(t, `{"data":[
	 {"sources":["https://anilist.co/anime/5"],"title":"Koro-sensei Q!","type":"MOVIE","episodes":1,
	  "animeSeason":{"season":"SPRING","year":2016},
	  "synonyms":["Assassination Classroom: Koro-sensei Q!"]},
	 {"sources":["https://anilist.co/anime/6"],"title":"Tenchi Muyou! in Love","type":"MOVIE","episodes":1,
	  "animeSeason":{"season":"SPRING","year":1996}}
	]}`)
	cases := []struct {
		titles []string
		id     int
		want   bool
		why    string
	}{
		{[]string{"Assassination Classroom"}, 5, true, "upstream names it as this series' work, by synonym"},
		{[]string{"Ai Tenchi Muyou"}, 6, false, "a 1996 film of an earlier part of the franchise is not this 2014 series'"},
		{[]string{"Ko"}, 5, false, "a two-character title matches most of the catalogue once folded"},
	}
	for _, c := range cases {
		m := importer.Merge{AnilistID: c.id, Linked: true}
		if got := titleExtends(c.titles, m, db); got != c.want {
			t.Errorf("titleExtends(%q, %d) = %v, want %v — %s", c.titles, c.id, got, c.want, c.why)
		}
	}
}

func offlineFromJSON(t *testing.T, doc string) *offlinedb.Database {
	t.Helper()
	db, err := offlinedb.Parse(strings.NewReader(doc))
	if err != nil {
		t.Fatal(err)
	}
	return db
}

