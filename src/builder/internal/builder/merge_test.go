// A series the import wrote: bare slots, no authored ids, and a comment where
// the films begin — which is the shape that broke an earlier version of this.
const seriesWithComment = `# Authored override — 2021 catalogue import.
series:
  id: show
  titles:
    original: ショー
    translations: { ja-Latn: Show }
  seasons:
    - id: show-s1
      number: 1
  movies:
    # Added by the 2021 import.
    - id: show-film
# One linear storyline: episodes carry a continuous absoluteNumber.
numbered: [show]
`

const recordWithComment = `# Generated by ` + "`builder build`" + ` — do not edit.
series:
  id: show
  seasons:
    - id: show-s1
      number: 1
      releaseYear: 2021
      externalIds:
        anilistId: 100
  movies:
    - id: show-film
      releaseYear: 2021
      externalIds:
        anilistId: 200
`

func film(id, title string, year int) importer.Merge {
	return importer.Merge{Title: title, AnilistID: id2(id), Type: offlinedb.TypeMovie, Year: year, Linked: true}
}

func id2(s string) int {
	n := 0
	for _, r := range s {
		n = n*10 + int(r-'0')
	}
	return n
}

// A second film must land inside the existing `movies:` block. Appending it
// after the seasons instead produced a file with two `movies:` keys, which YAML
// rejects outright — jujutsu-kaisen, whose films open with a comment.
func TestAFilmIsAddedInsideAnExistingBlockEvenAfterAComment(t *testing.T) {
	got, why := plan(seriesWithComment, recordWithComment, "show", film("300", "Show: The Movie 2", 2023), map[string]bool{})
	if why != "" {
		t.Fatalf("refused: %s", why)
	}
	if n := strings.Count(got, "  movies:"); n != 1 {
		t.Fatalf("the file has %d movies keys, want 1:\n%s", n, got)
	}
	if !strings.Contains(got, "- id: show-film-2") {
		t.Errorf("the new film is missing:\n%s", got)
	}
	if !strings.Contains(got, "# Added by the 2021 import.") {
		t.Errorf("the existing comment was dropped:\n%s", got)
	}
	// The slot that resolved by title has to be pinned, or the count the build
	// matches the kind by no longer holds and it stops resolving.
	if !strings.Contains(got, "anilistId: 200") {
		t.Errorf("the existing film's resolved id was not pinned:\n%s", got)
	}
}

// A season is only appended where it aired after everything already there.
// Anything earlier would be claiming a position inside the run.
func TestASeasonThatDidNotAirLastIsRefused(t *testing.T) {
	early := importer.Merge{Title: "Show 0", AnilistID: 300, Type: offlinedb.TypeTV, Year: 2019, Linked: true}
	_, why := plan(seriesWithComment, recordWithComment, "show", early, map[string]bool{})
	if !strings.Contains(why, "did not air after every installment") {
		t.Errorf("why = %q, want the ordering refusal", why)
	}

	later := importer.Merge{Title: "Show 2", AnilistID: 301, Type: offlinedb.TypeTV, Year: 2023, Linked: true}
	got, why := plan(seriesWithComment, recordWithComment, "show", later, map[string]bool{})
	if why != "" {
		t.Fatalf("refused a trailing season: %s", why)
	}
	if !strings.Contains(got, "- id: show-s2\n      number: 2") {
		t.Errorf("the season is not numbered after the last:\n%s", got)
	}
}

